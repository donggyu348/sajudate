// 중복 없이 n개를 랜덤으로 뽑는다.
export function pickReviews(n = 6) {
  const pool = REVIEWS.slice();
  for (let i = pool.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0, Math.min(n, pool.length));
}
